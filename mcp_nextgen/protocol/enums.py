"""协议枚举。"""

from enum import Enum


class ApprovalLevel(str, Enum):
    L0_READ_ONLY = "L0_READ_ONLY"
    L1_DRY_RUN = "L1_DRY_RUN"
    L2_SANDBOX_PREP = "L2_SANDBOX_PREP"
    L3_SANDBOX_WRITE = "L3_SANDBOX_WRITE"
    L4_CONTROLLED_PRODUCTION = "L4_CONTROLLED_PRODUCTION"


class BackendKind(str, Enum):
    MOCK = "MOCK"
    LEGACY_ADAPTER = "LEGACY_ADAPTER"
    REAL_PLUGIN = "REAL_PLUGIN"


class DocumentRole(str, Enum):
    REFERENCE = "REFERENCE"
    TARGET = "TARGET"
    SANDBOX_COPY = "SANDBOX_COPY"
    WORKING_COPY = "WORKING_COPY"
    MOCK_DOCUMENT = "MOCK_DOCUMENT"


class JobStatus(str, Enum):
    CREATED = "CREATED"
    VALIDATING = "VALIDATING"
    PLANNED = "PLANNED"
    RUNNING = "RUNNING"
    PAUSED = "PAUSED"
    COMPLETED = "COMPLETED"
    FAILED = "FAILED"
    CANCELLED = "CANCELLED"
    MANUAL_SAVE_REQUIRED = "MANUAL_SAVE_REQUIRED"
